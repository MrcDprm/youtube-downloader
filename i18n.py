DECIMAL = {"tr": ",", "en": "."}


def translate(lang, key, **params):
    text = MESSAGES.get(lang, MESSAGES["en"]).get(key) or MESSAGES["en"].get(key, key)
    return text.format(**params) if params else text


def format_duration(seconds):
    """3725 → "1:02:05", 65 → "1:05"."""
    seconds = max(0, round(seconds))
    hours, rest = divmod(seconds, 3600)
    minutes, seconds = divmod(rest, 60)
    return f"{hours}:{minutes:02d}:{seconds:02d}" if hours else f"{minutes}:{seconds:02d}"


def format_speed(bytes_per_second, lang):
    """2_400_000 → "2,3 MB/sn" (Türkçe) ya da "2.3 MB/s"."""
    value, unit = bytes_per_second / 1024, "KB"
    if value >= 1024:
        value, unit = value / 1024, "MB"
    text = f"{value:.1f}" if value < 100 else f"{value:.0f}"
    return translate(lang, "speed", value=text.replace(".", DECIMAL.get(lang, ".")), unit=unit)
